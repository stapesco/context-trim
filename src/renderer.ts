/**
 * Renders the scanned-file list into a single Markdown digest.
 *
 * Format is stable and human-readable so users can paste it into any
 * AI chat assistant. Section per file with a fenced code block.
 */

import type { ScannedFile } from "./scanner.js";
import { VERSION_STRING } from "./cli.js";

export interface DigestOptions {
  title: string;
  root: string;
  totalBytes: number;
  /** Maximum characters per file body. Excess is truncated with a marker. */
  perFileCharLimit: number;
  /** Maximum total characters for the whole digest. */
  totalCharLimit: number;
}

export interface DigestResult {
  markdown: string;
  truncatedFiles: string[];
  truncated: boolean;
}

const DEFAULT_PER_FILE_LIMIT = 50_000;
const DEFAULT_TOTAL_LIMIT = 800_000;

export async function renderDigest(
  files: ScannedFile[],
  readContent: (abs: string) => Promise<string>,
  options: Partial<DigestOptions> = {},
): Promise<DigestResult> {
  const perFileLimit = options.perFileCharLimit ?? DEFAULT_PER_FILE_LIMIT;
  const totalLimit = options.totalCharLimit ?? DEFAULT_TOTAL_LIMIT;

  const header = [
    `# ${options.title ?? "Codebase Context"}`,
    ``,
    `Generated by ${VERSION_STRING}`,
    `Root: \`${options.root ?? "."}\``,
    `Files: ${files.length}`,
    `Bytes: ${options.totalBytes ?? 0}`,
    ``,
    `---`,
    ``,
  ].join("\n");

  const truncatedFiles: string[] = [];
  const parts: string[] = [header];
  let totalChars = header.length;
  let truncated = false;

  for (const file of files) {
    let body: string;
    try {
      body = await readContent(file.path);
    } catch {
      body = `(unable to read file)`;
    }
    let truncatedBody = false;
    if (body.length > perFileLimit) {
      body = body.substring(0, perFileLimit);
      truncatedBody = true;
    }

    const sectionHeader = `## ${file.relPath}\n`;
    // Choose a fence length strictly greater than the longest run of
    // consecutive backticks in the body, so embedded ``` blocks inside the
    // file don't terminate our outer fence. CommonMark-compliant.
    const fenceLen = longestBacktickRun(body) + 1;
    const fence = "`".repeat(Math.max(fenceLen, 3));
    const section = `${sectionHeader}${fence}\n${body}${fence}\n`;

    if (totalChars + section.length > totalLimit) {
      truncated = true;
      break;
    }

    parts.push(section);
    totalChars += section.length;
    if (truncatedBody) {
      truncatedFiles.push(file.relPath);
    }
  }

  const trailer = `\n---\n\nEnd of digest.\n`;
  parts.push(trailer);

  return {
    markdown: parts.join("\n"),
    truncatedFiles,
    truncated,
  };
}

/**
 * Return the length of the longest run of consecutive backticks in `text`.
 * Used to pick a fenced-code-block fence length that won't be terminated
 * by an embedded ``` sequence inside a file body.
 */
export function longestBacktickRun(text: string): number {
  let best = 0;
  let cur = 0;
  for (let i = 0; i < text.length; i++) {
    if (text.charCodeAt(i) === 96) {
      cur++;
      if (cur > best) best = cur;
    } else {
      cur = 0;
    }
  }
  return best;
}